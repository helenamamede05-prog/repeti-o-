package flamingo.aprendendo.basico;

public class OperdaoresParte06 {

     // Incremento e Decremento

    static void main() {
        int contador = 0;

        contador = contador + 1000;
        contador += 1000;
        contador ++;


        contador = contador - 1000;
        contador -= 100;
        contador --;

        System.out.println(contador);
    }
}




